"""Migrate deployed Lepton Quest launchers to inherit Steam's real app ID.

Preview is the default. Pass --apply to update only generated Quest launchers
whose SteamAppId export is still a numeric saved fallback.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
import re
import stat
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

try:
    ROOT = Path(__file__).resolve().parents[1]
except NameError:  # `python3 -` on the Frame for a no-upload preview
    ROOT = None
AGENT_PATH = ROOT / "agent" / "frameport_agent.py" if ROOT else None
INSTALLED_AGENT_PATH = Path.home() / ".local/share/frameport/agent/frameport_agent.py"
EXPORT_RE = re.compile(
    r"(?m)^(?P<prefix>[ \t]*export[ \t]+SteamAppId=)"
    r"(?P<quote>['\"]?)(?P<appid>[0-9]+)(?P=quote)(?P<suffix>[ \t\r]*)$"
)
ALL_EXPORT_RE = re.compile(r"(?m)^[ \t]*export[ \t]+SteamAppId=[^\r\n]*$")
TARGET_EXPORT = 'export SteamAppId="${SteamAppId:-%s}"'
GENERATED_MARKER = "Generated by FramePort."
MIGRATION_RE = re.compile(r'(?m)^[ \t]*export[ \t]+SteamAppId="\$\{SteamAppId:-[0-9]+\}"[ \t\r]*$')


class RepairError(RuntimeError):
    pass


def load_agent(path: Path | None = None):
    """Load FramePort's installed agent helpers without executing its CLI."""
    path = path or default_agent_path()
    spec = importlib.util.spec_from_file_location("frameport_identity_agent", path)
    if spec is None or spec.loader is None:
        raise RepairError(f"can't load FramePort agent at {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def default_agent_path() -> Path:
    # On a Frame, its installed agent may be newer than the local desktop source.
    if INSTALLED_AGENT_PATH.is_file():
        return INSTALLED_AGENT_PATH
    if AGENT_PATH and AGENT_PATH.is_file():
        return AGENT_PATH
    raise RepairError("FramePort agent not found; pass --agent or run on a Frame with its installed agent")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _safe_regular_file(path: Path) -> bool:
    try:
        return not path.is_symlink() and stat.S_ISREG(path.lstat().st_mode)
    except OSError:
        return False


def _deployed_packages(anchor_root: Path, agent=None) -> tuple[list[dict[str, Any]], list[str]]:
    """Read deployment records and fail closed for incomplete/conflicting entries."""
    candidates: list[dict[str, Any]] = []
    skipped: list[str] = []
    if not anchor_root.exists():
        return candidates, [f"deployment root missing: {anchor_root}"]
    if anchor_root.is_symlink() or not anchor_root.is_dir():
        return candidates, [f"deployment root is not a real directory: {anchor_root}"]
    try:
        entries = sorted(anchor_root.iterdir())
    except OSError as exc:
        return candidates, [f"can't enumerate deployment root: {exc}"]
    try:
        mount_table = agent.mounts() if agent else None
    except Exception as exc:
        return candidates, [f"can't inspect mounted drives: {exc}"]
    for directory in entries:
        if directory.is_symlink() or not directory.is_dir():
            continue
        dep_path = directory / "deployment.json"
        if not dep_path.exists():
            if (directory / "launch.sh").exists() or (directory / "launch.sh").is_symlink():
                skipped.append(f"{directory.name}: launcher has no deployment record")
            continue
        if not _safe_regular_file(dep_path):
            skipped.append(f"{directory.name}: deployment record is not a regular file")
            continue
        try:
            dep = json.loads(dep_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            skipped.append(f"{directory.name}: unreadable deployment record ({exc})")
            continue
        if (
            not isinstance(dep, dict)
            or not isinstance(dep.get("package"), str)
            or not dep["package"]
            or not dep.get("appid")
        ):
            skipped.append(f"{directory.name}: unknown deployment record")
            continue
        package = dep["package"]
        if package != directory.name:
            skipped.append(f"{directory.name}: package identity conflicts with deployment record ({package})")
            continue
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z0-9_]+)+", package):
            skipped.append(f"{directory.name}: invalid package identity")
            continue
        kind = dep.get("kind", "quest")
        if kind in ("linux", "pcvr"):
            continue
        if kind != "quest":
            skipped.append(f"{package}: unknown deployment kind {kind!r}")
            continue
        try:
            base = Path(dep.get("base") or directory)
        except TypeError:
            skipped.append(f"{package}: invalid deployment base")
            continue
        if not base.is_absolute():
            skipped.append(f"{package}: deployment base is not absolute")
            continue
        try:
            if agent and agent.drive_missing(str(base), mount_table):
                skipped.append(f"{package}: deployment drive is missing")
                continue
            base_resolved = base.resolve(strict=True)
        except OSError:
            skipped.append(f"{package}: deployment drive/base is missing")
            continue
        # The deployment record is the authority for the Lepton APK location.
        lepton_dir = base_resolved / "lepton-app"
        apk = lepton_dir / "game.apk"
        if lepton_dir.is_symlink() or apk.is_symlink() or not apk.is_file():
            skipped.append(f"{package}: Lepton APK is missing or unsafe")
            continue
        launch = directory / "launch.sh"
        if not _safe_regular_file(launch):
            skipped.append(f"{package}: launcher missing or is not a regular file")
            continue
        try:
            text = launch.read_bytes().decode("utf-8")
        except (OSError, UnicodeError) as exc:
            skipped.append(f"{package}: launcher unreadable ({exc})")
            continue
        if GENERATED_MARKER not in text or '"$app_dir/lepton-app"' not in text:
            skipped.append(f"{package}: launcher is not a generated Lepton Quest launcher")
            continue
        candidates.append({"package": package, "path": launch, "text": text, "dep": dep})
    return candidates, skipped


def _devkit_identity(agent, package: str) -> str:
    try:
        gameid = agent.devkit_gameid(package)
        appid = agent.devkit_appid(gameid) if gameid else None
    except Exception as exc:  # best-effort read-only lookup; migration still preserves saved fallback
        return f"unavailable ({type(exc).__name__}: {exc})"
    return str(appid) if appid is not None else "unavailable"


def _bash_syntax_error(text: str) -> str | None:
    """Parse launcher text without executing it or inheriting shell startup hooks."""
    env = os.environ.copy()
    env.pop("BASH_ENV", None)
    env.pop("ENV", None)
    try:
        result = subprocess.run(
            ["bash", "-n"], input=text, text=True, capture_output=True, env=env, check=False
        )
    except OSError as exc:
        return f"couldn't run bash -n ({exc})"
    if result.returncode:
        detail = (result.stderr or result.stdout).strip().splitlines()
        return detail[-1] if detail else f"bash -n exited {result.returncode}"
    return None


def plan(anchor_root: Path, agent=None) -> tuple[list[dict[str, Any]], list[str]]:
    agent = agent or load_agent(default_agent_path())
    candidates, skipped = _deployed_packages(anchor_root, agent)
    changes = []
    for record in candidates:
        text = record["text"]
        syntax_error = _bash_syntax_error(text)
        if syntax_error:
            skipped.append(f"{record['package']}: launcher failed bash -n: {syntax_error}")
            continue
        exports = list(ALL_EXPORT_RE.finditer(text))
        if len(exports) > 1:
            skipped.append(f"{record['package']}: conflicting SteamAppId exports")
            continue
        matches = list(EXPORT_RE.finditer(text))
        if not matches:
            if MIGRATION_RE.search(text):
                skipped.append(f"{record['package']}: already fixed; preserving launcher")
            else:
                skipped.append(f"{record['package']}: no simple numeric SteamAppId export to migrate")
            continue
        if len(matches) != 1:
            skipped.append(f"{record['package']}: conflicting SteamAppId exports")
            continue
        match = matches[0]
        # Require the precise legacy generated export. Preserve the app's chosen saved fallback.
        appid = match.group("appid")
        indentation = match.group("prefix").split("export", 1)[0]
        updated = (
            text[:match.start()]
            + indentation
            + (TARGET_EXPORT % appid)
            + match.group("suffix")
            + text[match.end():]
        )
        syntax_error = _bash_syntax_error(updated)
        if syntax_error:
            skipped.append(f"{record['package']}: proposed launcher failed bash -n: {syntax_error}")
            continue
        record.update(status="ready", before=text, after=updated, appid=appid,
                      devkit_appid=_devkit_identity(agent, record["package"]))
        changes.append(record)
    return changes, skipped


def _atomic_replace(path: Path, expected: bytes, updated: bytes) -> None:
    """Replace only if the original is unchanged, preserving mode and atomicity."""
    try:
        current = path.read_bytes()
        info = path.lstat()
    except OSError as exc:
        raise RepairError(f"{path}: couldn't re-read before replacement: {exc}") from None
    if not stat.S_ISREG(info.st_mode) or path.is_symlink() or sha256(current) != sha256(expected):
        raise RepairError(f"{path}: changed after preview; refusing replacement")
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    temp = Path(temp_name)
    try:
        with os.fdopen(fd, "wb") as output:
            output.write(updated)
            output.flush()
            os.fsync(output.fileno())
        os.chmod(temp, stat.S_IMODE(info.st_mode))
        if sha256(path.read_bytes()) != sha256(expected):
            raise RepairError(f"{path}: changed during replacement; refusing replacement")
        os.replace(temp, path)
    finally:
        try:
            temp.unlink()
        except FileNotFoundError:
            pass


def _write_backup(path: Path, data: bytes) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as output:
        output.write(data)
        output.flush()
        os.fsync(output.fileno())


def apply(changes: list[dict[str, Any]], backup_dir: Path) -> list[Path]:
    if not changes:
        return []
    backup_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    if backup_dir.is_symlink() or not backup_dir.is_dir():
        raise RepairError(f"backup path is not a real directory: {backup_dir}")
    backup_paths = [backup_dir / f"{record['package']}.launch.sh" for record in changes]
    if any(path.exists() or path.is_symlink() for path in backup_paths):
        raise RepairError("one or more per-package backups already exist in the selected backup directory")
    saved: list[dict[str, Any]] = []
    written: list[dict[str, Any]] = []
    try:
        for record in changes:
            path: Path = record["path"]
            before = record["before"].encode("utf-8")
            after = record["after"].encode("utf-8")
            backup = backup_dir / f"{record['package']}.launch.sh"
            if backup.exists() or backup.is_symlink():
                raise RepairError(f"backup already exists: {backup}")
            _write_backup(backup, before)
            saved.append({"path": path, "backup": backup, "before": before, "after": after})
            _atomic_replace(path, before, after)
            written.append(saved[-1])
    except Exception:
        rollback_errors = []
        for item in reversed(written):
            try:
                current = item["path"].read_bytes()
                if sha256(current) != sha256(item["after"]):
                    raise RepairError(f"{item['path']}: changed during rollback")
                _atomic_replace(item["path"], item["after"], item["before"])
            except Exception as exc:
                rollback_errors.append(str(exc))
        if rollback_errors:
            raise RepairError("migration failed; rollback also failed: " + "; ".join(rollback_errors)) from None
        raise
    return [item["backup"] for item in saved]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--preview", action="store_true", help="show the planned changes without writing (default)")
    mode.add_argument("--apply", action="store_true", help="write the planned launcher changes")
    parser.add_argument("--anchor-root", type=Path, help="override the FramePort deployment root (tests/recovery)")
    parser.add_argument("--backup-dir", type=Path, help="where to keep small original launchers during --apply")
    parser.add_argument("--agent", type=Path, help="FramePort agent source; defaults to the installed Frame agent")
    args = parser.parse_args(argv)
    try:
        agent = load_agent(args.agent or default_agent_path())
        anchor_root = args.anchor_root or Path(agent.ANCHORS)
        changes, skipped = plan(anchor_root, agent)
        print(f"FramePort root: {anchor_root}")
        if args.apply:
            backup_dir = args.backup_dir or (
                Path(agent.HOME)
                / ".local/share/frameport/steam-identity-backups"
                / time.strftime("%Y%m%d-%H%M%S")
            )
            backups = apply(changes, backup_dir)
            print(f"Applied {len(backups)} launcher migration(s); originals: {backup_dir}")
            if not backups:
                print("No files changed.")
        else:
            print(f"Preview: {len(changes)} launcher migration(s); rerun with --apply to write")
        for record in changes:
            print(
                f"  {record['package']}: saved fallback {record['appid']}; "
                f"current devkit ID {record['devkit_appid']}; {record['path']}"
            )
        for record in skipped:
            print(f"  skipped: {record}")
        return 0
    except (OSError, RepairError) as exc:
        print(f"repair failed: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
