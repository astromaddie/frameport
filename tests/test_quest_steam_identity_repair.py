def test_missing_drive_is_skipped(tmp_path):
    missing = tmp_path / "absent-card/FramePort/com.example.card"
    root, _anchor, _launch = _tree(tmp_path, "com.example.card", base=missing)
    # Fixture created an apparent path; the FramePort drive inventory still marks it absent.
    changes, skipped = repair.plan(root, _agent(missing=(missing,)))
    assert changes == []
    assert any("deployment drive is missing" in message for message in skipped)


def test_changed_launcher_is_not_overwritten(tmp_path):
    root, _anchor, launch = _tree(tmp_path)
    changes, _ = repair.plan(root, _agent())
    launch.write_text("user edit\n")
    with pytest.raises(repair.RepairError, match="changed after preview"):
        repair.apply(changes, tmp_path / "backups")
    assert launch.read_text() == "user edit\n"


def test_partial_failure_rolls_back_prior_launcher_updates(tmp_path, monkeypatch):
    root, _anchor1, first = _tree(tmp_path, "com.example.first")
    _tree(tmp_path, "com.example.second")
    changes, _ = repair.plan(root, _agent())
    before = {Path(c["path"]): Path(c["path"]).read_bytes() for c in changes}
    original_replace = repair._atomic_replace
    calls = 0

    def fail_on_second(path, expected, updated):
        nonlocal calls
        calls += 1
        if calls == 2:
            raise repair.RepairError("injected replacement failure")
        return original_replace(path, expected, updated)

    monkeypatch.setattr(repair, "_atomic_replace", fail_on_second)
    with pytest.raises(repair.RepairError, match="injected replacement failure"):
        repair.apply(changes, tmp_path / "backups")
    assert first.read_bytes() == before[first]
    assert all(path.read_bytes() == original for path, original in before.items())
