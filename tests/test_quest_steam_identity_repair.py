import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "scripts/repair_quest_steam_identity.py"
SPEC = importlib.util.spec_from_file_location("quest_steam_identity_repair", SCRIPT)
assert SPEC and SPEC.loader
repair = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = repair
SPEC.loader.exec_module(repair)


def _tree(tmp_path, package="com.example.game", *, kind="quest", base=None, launcher=None):
    root = tmp_path / "anchors"
    anchor = root / package
    anchor.mkdir(parents=True)
    game_base = Path(base) if base else anchor
    (game_base / "lepton-app").mkdir(parents=True, exist_ok=True)
    (game_base / "lepton-app/game.apk").write_bytes(b"apk")
    deployment = {"package": package, "appid": 5150, "base": str(game_base)}
    if kind is not None:
        deployment["kind"] = kind
    (anchor / "deployment.json").write_text(json.dumps(deployment))
    launch = anchor / "launch.sh"
    launch.write_bytes((launcher or _launcher()).encode())
    launch.chmod(0o751)
    return root, anchor, launch


def _launcher(export='export SteamAppId=5150'):
    return ('#!/usr/bin/env bash\n'
            '# Steam Frame launcher for Game. Generated by FramePort.\n'
            'app_dir=/tmp/game\n'
            f'{export}\n'
            'exec "$app_dir/lepton-app"\n')


def _agent(missing=()):
    return SimpleNamespace(
        mounts=lambda: [],
        drive_missing=lambda base, table: str(base) in {str(p) for p in missing},
        devkit_gameid=lambda package: f"devkit-{package}",
        devkit_appid=lambda gameid: 991234 if gameid else None,
    )


@pytest.mark.parametrize("export", ["export SteamAppId=5150", "export SteamAppId='5150'", 'export SteamAppId="5150"'])
def test_preview_and_apply_change_only_numeric_export_and_keep_mode(tmp_path, export):
    root, _anchor, launch = _tree(tmp_path, launcher=_launcher(export))
    original = launch.read_bytes()
    changes, skipped = repair.plan(root, _agent())
    assert not skipped
    assert len(changes) == 1
    assert changes[0]["appid"] == "5150"
    assert changes[0]["devkit_appid"] == "991234"
    assert launch.read_bytes() == original  # preview never writes

    backups = repair.apply(changes, tmp_path / "backups")
    updated = launch.read_bytes()
    assert updated == original.replace(export.encode(), b'export SteamAppId="${SteamAppId:-5150}"')
    assert launch.stat().st_mode & 0o777 == 0o751
    assert len(backups) == 1 and backups[0].read_bytes() == original
    assert subprocess.run(["bash", "-n", str(launch)]).returncode == 0

    second, second_skipped = repair.plan(root, _agent())
    assert second == []
    assert any("already fixed" in message for message in second_skipped)


@pytest.mark.parametrize(("inherited", "expected"), [("123456", "123456"), ("", "5150"), (None, "5150")])
def test_shell_uses_inherited_appid_or_saved_fallback(tmp_path, inherited, expected):
    root, _anchor, launch = _tree(tmp_path)
    changes, _ = repair.plan(root, _agent())
    repair.apply(changes, tmp_path / "backups")
    env = dict(os.environ)
    if inherited is None:
        env.pop("SteamAppId", None)
    else:
        env["SteamAppId"] = inherited
    export_line = next(line for line in launch.read_text().splitlines() if "export SteamAppId=" in line)
    result = subprocess.run(["bash", "-c", f'{export_line}\nprintf %s "$SteamAppId"'],
                           capture_output=True, text=True, env=env, check=True)
    assert result.stdout == expected


def test_crlf_and_other_launcher_bytes_are_preserved(tmp_path):
    original = (
        _launcher()
        .replace("\n", "\r\n")
        .replace("app_dir=/tmp/game", "app_dir='/tmp/a path'\r\n# _logcat_keeper helper")
    )
    root, _anchor, launch = _tree(tmp_path, launcher=original)
    before = launch.read_bytes()
    changes, _ = repair.plan(root, _agent())
    repair.apply(changes, tmp_path / "backups")
    after = launch.read_bytes()
    assert after == before.replace(b"export SteamAppId=5150", b'export SteamAppId="${SteamAppId:-5150}"')
    assert b"_logcat_keeper helper" in after
    second, second_skipped = repair.plan(root, _agent())
    assert second == []
    assert any("already fixed" in message for message in second_skipped)


def test_malformed_generated_launcher_is_rejected_before_backup_or_write(tmp_path, monkeypatch):
    root, _anchor, launch = _tree(tmp_path, launcher=_launcher() + "if then\n")
    before = launch.read_bytes()
    startup = tmp_path / "bash-env"
    marker = tmp_path / "bash-env-ran"
    startup.write_text(f"touch {marker}\n")
    monkeypatch.setenv("BASH_ENV", str(startup))

    changes, skipped = repair.plan(root, _agent())
    assert changes == []
    assert any("launcher failed bash -n" in message for message in skipped)
    assert not marker.exists()
    backup_dir = tmp_path / "backups"
    assert repair.apply(changes, backup_dir) == []
    assert not backup_dir.exists()
    assert launch.read_bytes() == before


def test_exclusions_and_unknown_or_conflicting_records_fail_closed(tmp_path):
    root, *_ = _tree(tmp_path)
    _tree(tmp_path, "com.example.linux", kind="linux")
    _tree(tmp_path, "com.example.pcvr", kind="pcvr")
    _tree(tmp_path, "com.example.unknown", kind="android")
    _tree(tmp_path, "com.example.badrecord", launcher=_launcher())
    bad = root / "com.example.badrecord/deployment.json"
    bad.write_text(json.dumps({"package": "com.someone.else", "appid": 1, "base": str(root / "com.example.badrecord")}))
    symlink_root, symlink_anchor, _ = _tree(tmp_path, "com.example.symlink")
    target = symlink_anchor / "real-launch.sh"
    target.write_bytes(_launcher().encode())
    (symlink_anchor / "launch.sh").unlink()
    (symlink_anchor / "launch.sh").symlink_to(target)
    _tree(tmp_path, "com.example.conflict", launcher=_launcher() + "export SteamAppId=99\n")

    changes, skipped = repair.plan(root, _agent())
    assert [change["package"] for change in changes] == ["com.example.game"]
    assert any("unknown deployment kind" in message for message in skipped)
    assert any("conflicts with deployment record" in message for message in skipped)
    assert any("launcher missing or is not a regular file" in message for message in skipped)
    assert any("conflicting SteamAppId exports" in message for message in skipped)


